"""Multi-page report PDFs using the standard PDF font set.

Characters that Helvetica cannot draw are replaced. The CSV export keeps the
original text.
"""


def _encode(value):
    text = "" if value is None else str(value)
    # Keep the file ASCII. High bytes in a hand-built PDF are a common reason
    # readers treat a damaged file as password-protected.
    encoded = text.encode("ascii", errors="replace").decode("ascii")
    return encoded.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def _clip(value, width, font_size):
    text = "" if value is None else str(value)
    max_chars = max(int(width / (font_size * 0.48)), 1)
    if len(text) <= max_chars:
        return text
    return text[: max_chars - 3] + "..."


def build_pdf(*, title, meta_lines, headers, rows, orientation="landscape"):
    landscape = orientation == "landscape"
    page_width, page_height = (842, 595) if landscape else (595, 842)
    margin = 36
    font_size = 8
    title_size = 13
    line_height = 12
    usable = page_width - (margin * 2)
    column_width = usable / max(len(headers), 1)
    header_height = 36 + (line_height * (len(meta_lines) + 1))
    footer_height = 22
    top = page_height - margin - header_height
    bottom = margin + footer_height
    rows_per_page = max(int((top - bottom) / line_height) - 1, 1)
    body = rows or [["No records match these filters."] + [""] * (len(headers) - 1)]
    page_rows = [body[index:index + rows_per_page] for index in range(0, len(body), rows_per_page)] or [[]]
    page_count = len(page_rows)

    def page_stream(page_number, table_rows):
        commands = ["BT", f"/F1 {title_size} Tf", f"1 0 0 1 {margin} {page_height - margin - 14} Tm ({_encode('SGR 200HA+')}) Tj"]
        commands.append(f"/F1 9 Tf 1 0 0 1 {margin} {page_height - margin - 28} Tm ({_encode('Farmer & Input Management System')}) Tj")
        commands.append(f"/F1 11 Tf 1 0 0 1 {margin} {page_height - margin - 44} Tm ({_encode(_clip(title, usable, 11))}) Tj")
        y = page_height - margin - 60
        commands.append(f"/F1 {font_size} Tf")
        for line in meta_lines:
            commands.append(f"1 0 0 1 {margin} {y:.2f} Tm ({_encode(_clip(line, usable, font_size))}) Tj")
            y -= line_height
        y = top
        for index, header in enumerate(headers):
            x = margin + (index * column_width)
            commands.append(f"1 0 0 1 {x:.2f} {y:.2f} Tm ({_encode(_clip(header, column_width - 4, font_size))}) Tj")
        y -= line_height
        for row in table_rows:
            for index, cell in enumerate(row):
                x = margin + (index * column_width)
                commands.append(f"1 0 0 1 {x:.2f} {y:.2f} Tm ({_encode(_clip(cell, column_width - 4, font_size))}) Tj")
            y -= line_height
        footer = f"Generated by SGR 200HA+    Confidential - authorised use only    Page {page_number} of {page_count}"
        commands.append(f"1 0 0 1 {margin} {margin - 4:.2f} Tm ({_encode(_clip(footer, usable, font_size))}) Tj")
        commands.append("ET")
        return "\n".join(commands).encode("ascii", errors="replace")

    contents = [page_stream(number, rows_for_page) for number, rows_for_page in enumerate(page_rows, start=1)]
    objects = [b"1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj\n"]
    kids = " ".join(f"{4 + (index * 2)} 0 R" for index in range(page_count))
    objects.append(f"2 0 obj << /Type /Pages /Count {page_count} /Kids [{kids}] >> endobj\n".encode())
    objects.append(b"3 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> endobj\n")
    for index, stream in enumerate(contents):
        page_id = 4 + (index * 2)
        content_id = page_id + 1
        objects.append(
            (
                f"{page_id} 0 obj << /Type /Page /Parent 2 0 R /MediaBox [0 0 {page_width} {page_height}] "
                f"/Contents {content_id} 0 R /Resources << /Font << /F1 3 0 R >> >> >> endobj\n"
            ).encode()
        )
        objects.append(f"{content_id} 0 obj << /Length {len(stream)} >> stream\n".encode() + stream + b"\nendstream endobj\n")

    output = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = [0]
    for obj in objects:
        offsets.append(len(output))
        output.extend(obj)
    xref = len(output)
    output.extend(f"xref\n0 {len(offsets)}\n".encode())
    output.extend(b"0000000000 65535 f \n")
    for offset in offsets[1:]:
        output.extend(f"{offset:010d} 00000 n \n".encode())
    output.extend(
        f"trailer << /Size {len(offsets)} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode("ascii")
    )
    return bytes(output)
